const HEIGHT = 7;

function renderRows(text: string): string[] {
  const chars = text
    .toUpperCase()
    .split("")
    .map((c) => PIXELS[c])
    .filter(Boolean);

  const rows: string[] = [];
  for (let r = 0; r < HEIGHT; r++) {
    rows.push(
      chars
        .map((ch) => ch[r].map((p) => (p ? "██" : "  ")).join(""))
        .join("  ") // 2-space gap between letters
    );
  }
  return rows;
}

type AsciiLogoProps = {
  text: string;
  colorStart: string;
  colorEnd: string;
};

export function AsciiLogo({ text, colorStart, colorEnd }: AsciiLogoProps) {
  const rows = renderRows(text);

  return (
    <pre
      className="font-mono text-[0.68rem] leading-[1.22] overflow-x-auto select-none mb-5"
      style={{
        background: `linear-gradient(90deg, ${colorStart} 0%, ${colorEnd} 100%)`,
        WebkitBackgroundClip: "text",
        WebkitTextFillColor: "transparent",
        backgroundClip: "text",
      }}
      aria-hidden="true"
    >
      {rows.join("\n")}
    </pre>
  );
}
